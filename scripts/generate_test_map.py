"""Generate ``scripts/test_map.json``: the tests that reach each source file
through the app, read from per-test coverage contexts (G7).

``scripts/select_tests.py`` chooses the changed profile's tests by following
imports, and stops at the composition roots (``athena.main``, ``athena.web``,
``athena.web.router``), which import nearly everything. A test that reaches a
router, a browser page or a helper only through the app it builds therefore has
no import edge to follow. This map supplies those edges, and it is recorded,
not kept by hand: coverage.py, run with ``--cov-context=test``, notes which
test executed each line, and this script reduces that to

    source file under src/athena  ->  the test files that executed it

keeping, for each file, only the tests the import graph does not already
select for it (the tests that reach it *only* through the app). The selector
adds the graph back, so a change to a file selects every recorded test that
ran it. A file every one of whose recorded tests imports it keeps an empty
entry: it was recorded, and the graph is its whole answer. A file with no
entry is one no recorded test ran, which the selector cannot bound.

Granularity is the file on both sides: the selector selects test files, and a
line-level map would churn with every edit while saying little more. A test
file counts when any of its tests ran a line of the source file in setup, call
or teardown.

What the map leaves out, and why:

- Lines run at import time. Coverage records them under the empty context,
  which no test owns; the import graph covers what a module does at import.
- The selector's safety valves (``core/db.py``, the composition roots): a
  change to one runs the full suite whatever the map says.
- Files that more than half of the recorded test files run (``UBIQUITOUS``),
  such as the middleware every request passes through. Naming most of the
  suite tells the selector nothing, so such a file gets no entry; it is listed
  under ``ubiquitous`` with its count so the omission is visible in review.
  The selector treats it as unmapped: a change that reaches it only through
  the app runs the full suite, as it did before the map was generated.
- Templates, static assets and documents: coverage does not measure them, so
  the selector keeps hand entries for them (``TEST_MAP`` there).

A test added after the map was recorded is selected through the app only once
the map is regenerated; the scheduled ``Test map`` workflow
(``.github/workflows/test-map.yml``) records the whole suite weekly and fails
with the diff when the committed map is stale. It never commits: a person
regenerates the map and commits it.

Usage (from the checkout root):

    # Record the whole suite with per-test contexts and rewrite the map (one
    # command; it runs the suite, so it takes as long as the product gate):
    .venv/bin/python scripts/generate_test_map.py --record
    # The same for some test files only (a partial map; say so when you commit):
    .venv/bin/python scripts/generate_test_map.py --record tests/test_web.py
    # Rewrite the map from coverage data already recorded with contexts:
    .venv/bin/python scripts/generate_test_map.py --data PATH [--data PATH ...]
    # Exit 1 and print the diff when the committed map differs from the data:
    .venv/bin/python scripts/generate_test_map.py --check --data PATH ...

``--output PATH`` also writes the regenerated map to PATH (the scheduled job
uploads it). The ordinary gate never records coverage: the selector reads the
committed map, and ``tests/test_generate_test_map.py`` tests this script on
synthetic coverage data.
"""

from __future__ import annotations

import argparse
from collections.abc import Iterable, Mapping
import difflib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

REPO = Path(__file__).resolve().parent.parent
MAP = "scripts/test_map.json"
SOURCE = "scripts/generate_test_map.py"
# A file more than this share of the recorded test files run gets no entry.
UBIQUITOUS = 0.5
ABOUT = (
    "Generated by scripts/generate_test_map.py from per-test coverage contexts; "
    "do not edit. For each source file, the test files that ran it and do not "
    "import it (the import graph selects those). scripts/select_tests.py reads it."
)


def _load_selector():
    path = Path(__file__).resolve().parent / "select_tests.py"
    spec = importlib.util.spec_from_file_location("athena_select_tests_for_map", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


select_tests = _load_selector()


class MapError(Exception):
    """The coverage data cannot produce a map; nothing is written."""


def _relative(measured: str, root: Path) -> str:
    path = Path(measured)
    if path.is_absolute():
        try:
            return path.resolve().relative_to(root.resolve()).as_posix()
        except ValueError:
            return path.as_posix()
    return path.as_posix()


def _test_file(context: str) -> str | None:
    """The test file a pytest-cov context (``<node id>|<phase>``) belongs to."""
    node, separator, _ = context.rpartition("|")
    if not separator:
        node = context
    path, separator, _ = node.partition("::")
    if not separator or not select_tests._is_test_file(path):
        return None
    return path


def observe(data_files: Iterable[Path], root: Path = REPO) -> dict[str, set[str]]:
    """Source path -> the test files whose contexts executed a line of it."""
    from coverage import CoverageData

    runs: dict[str, set[str]] = {}
    for data_file in data_files:
        if not Path(data_file).is_file():
            raise MapError(f"{data_file}: no coverage data")
        data = CoverageData(basename=str(data_file))
        data.read()
        if not any(_test_file(context) for context in data.measured_contexts()):
            raise MapError(
                f"{data_file}: no per-test contexts; record with --cov-context=test"
            )
        for measured in data.measured_files():
            source = _relative(measured, root)
            tests = {
                test
                for contexts in data.contexts_by_lineno(measured).values()
                for test in map(_test_file, contexts)
                if test is not None
            }
            if tests:
                runs.setdefault(source, set()).update(tests)
    return runs


def build(runs: Mapping[str, set[str]], index) -> dict[str, object]:
    """The map, as the JSON document the selector reads."""
    recorded = set().union(*runs.values()) if runs else set()
    if not recorded:
        raise MapError("the coverage data names no test file")
    limit = len(recorded) * UBIQUITOUS
    ubiquitous: dict[str, int] = {}
    entries: dict[str, list[str]] = {}
    for source in sorted(runs):
        if not (source.startswith("src/athena/") and source.endswith(".py")):
            continue
        if select_tests.valve(source) is not None:
            continue  # A change to it runs the full suite anyway.
        ran = runs[source]
        if len(ran) > limit:
            ubiquitous[source] = len(ran)
            continue
        module = index.path_modules.get(source)
        imported = (
            {index.module_paths[m] for m in index.reached(module)}
            if module is not None
            else set()
        )
        entries[source] = sorted(ran - imported)
    return {
        "about": ABOUT,
        "recorded_test_files": len(recorded),
        "ubiquitous_share": UBIQUITOUS,
        "ubiquitous": ubiquitous,
        "map": entries,
    }


def render(document: Mapping[str, object]) -> str:
    return json.dumps(document, indent=2) + "\n"


def generate(data_files: Iterable[Path], root: Path = REPO) -> str:
    index = select_tests.Index(root, with_map=False)
    return render(build(observe(data_files, root), index))


def record(tests: list[str], directory: Path, root: Path = REPO) -> Path:
    """Run pytest with per-test contexts; the data file it wrote."""
    data = directory / ".coverage"
    workers = os.environ.get("ATHENA_COVERAGE_WORKERS", "4")
    environment = {**os.environ, "COVERAGE_FILE": str(data)}
    command = [
        sys.executable,
        "-m",
        "pytest",
        "-q",
        "-n",
        workers,
        "-ra",
        "--strict-markers",
        "--cov",
        "--cov-config=pyproject.toml",
        "--cov-context=test",
        "--cov-report=",
        *tests,
    ]
    print("recording:", " ".join(command[1:]), flush=True)
    result = subprocess.run(command, cwd=root, env=environment, check=False)
    if result.returncode:
        # A failing run's coverage is not the suite's; never map it.
        raise MapError(f"pytest failed (exit {result.returncode}); map not written")
    return data


def check(text: str, committed: Path) -> int:
    current = committed.read_text(encoding="utf-8") if committed.exists() else ""
    if text == current:
        document = json.loads(text)
        print(
            f"test map is current: {len(document['map'])} source files, "
            f"{sum(len(tests) for tests in document['map'].values())} entries"
        )
        return 0
    sys.stdout.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            text.splitlines(keepends=True),
            f"{MAP} (committed)",
            f"{MAP} (from this run's coverage)",
        )
    )
    print(
        f"test map is stale: regenerate it with `.venv/bin/python {SOURCE} "
        f"--record` (or from this run's artifact) and commit {MAP}"
    )
    return 1


def main(argv: list[str] | None = None, root: Path = REPO) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument(
        "--data",
        action="append",
        type=Path,
        metavar="PATH",
        help="a coverage data file recorded with --cov-context=test (repeatable)",
    )
    source.add_argument(
        "--record",
        action="store_true",
        help="run pytest with per-test contexts first (TEST paths, or the suite)",
    )
    parser.add_argument("tests", nargs="*", metavar="TEST", help="with --record")
    parser.add_argument(
        "--check",
        action="store_true",
        help=f"write nothing to {MAP}; exit 1 with the diff if it is stale",
    )
    parser.add_argument(
        "--output", type=Path, help="also write the regenerated map to this path"
    )
    args = parser.parse_args(argv)
    if args.tests and not args.record:
        parser.error("TEST paths apply only to --record")
    try:
        if args.record:
            with tempfile.TemporaryDirectory(prefix="athena-test-map.") as scratch:
                text = generate([record(args.tests, Path(scratch), root)], root)
        else:
            text = generate(args.data, root)
    except MapError as error:
        print(f"test map not generated: {error}", file=sys.stderr)
        return 1
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
    if args.check:
        return check(text, root / MAP)
    (root / MAP).write_text(text, encoding="utf-8")
    document = json.loads(text)
    print(
        f"wrote {MAP}: {len(document['map'])} source files, "
        f"{sum(len(tests) for tests in document['map'].values())} entries, from "
        f"{document['recorded_test_files']} recorded test files"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
